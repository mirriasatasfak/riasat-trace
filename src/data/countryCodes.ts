export interface PrefixRoute {
  prefix: string; // e.g. "300", "98", "415", "17"
  carrier: string;
  circle?: string;
  lineType?: 'mobile' | 'landline' | 'voip' | 'toll_free';
}

export interface CountryCodeItem {
  code: string;       // e.g. "+91"
  name: string;       // e.g. "India"
  flag: string;       // e.g. "🇮🇳"
  iso: string;        // e.g. "IN"
  alpha3: string;     // e.g. "IND"
  capital: string;    // e.g. "New Delhi"
  timezone: string;   // e.g. "UTC+05:30 (IST)"
  regulatoryBody: string; // e.g. "Telecom Regulatory Authority of India (TRAI)"
  mcc: string;        // e.g. "404, 405"
  sample: string;     // e.g. "9876543210"
  length: number[];   // allowed lengths e.g. [10]
  carriers: string[]; // e.g. ["Reliance Jio", "Bharti Airtel", "Vodafone Idea", "BSNL"]
  routes?: PrefixRoute[];
}

